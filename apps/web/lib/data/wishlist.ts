/** Все желания, отсортированные по статусу: открытые → в работе → подарено. */
export function sortWishes(wishes: Wish[]): Wish[] {
  const order: Record<WishStatus, number> = { open: 0, claimed: 1, fulfilled: 2 };
  return [...wishes].sort((a, b) => order[statusOf(a)] - order[statusOf(b)]);
}

/** Статус желания по его полям. */
export function statusOf(wish: Wish): WishStatus {
  if (wish.fulfilled) return "fulfilled";
  if (wish.claimerId) return "claimed";
  return "open";
}
