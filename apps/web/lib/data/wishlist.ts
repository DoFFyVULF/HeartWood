// Данные страницы «Список желаний» (/wishlist) — единый источник правды
// для мечтаний и подарков пары.
//
// Вишлист — самый «игровой» хаб: проще целей, без сроков и прогресса.
// Здесь можно три вещи:
//   «я мечтаю» — добавить желание (за себя или за партнёра),
//   «я подарю» — взять желание партнёра в работу (claim) — так ему приятно
//     и немного интригующе, потому что автор видит только «кто-то готовит»,
//   «подарено» — отметить, что желание исполнилось.
//
// Каждое желание проходит путь: в списке → готовится подарок → подарено.
// Seed-желания иммутабельны; пользовательские добавляются в localStorage
// (см. features/world/wishlist/useWishlist.ts).

/** Кто загадал желание — id участника из coupleProfile. */
export type AuthorId = "dima" | "anya";

/** Статус желания — определяет раздел страницы и доступные действия. */
export type WishStatus = "open" | "claimed" | "fulfilled";

export interface Wish {
  /** Стабильный id; у seeds — строки вида "seed-…". */
  id: string;
  title: string;
  description?: string;
  /** Кто загадал — «Мечта Димы» / «Мечта Ани». */
  wisherId: AuthorId;
  /**
   * Кто взялся дарить (только партнёр мечтателя). Автор желания НЕ может
   * заклеймить сам себя — иначе теряется сюрприз. Пусто = никто не готовит.
   */
  claimerId?: AuthorId;
  /** Подарено — желание сбылось и уходит в третий раздел. */
  fulfilled?: boolean;
  /** Для пользовательских — кто добавил («Добавила Аня»). */
  createdBy?: AuthorId;
}

